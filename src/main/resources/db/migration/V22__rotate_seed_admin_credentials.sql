-- 주석으로 함께 남아 있어 사실상 공개 자격증명이었다. V5 자체는 이미 적용된
-- 마이그레이션이라 수정하면 Flyway checksum 이 깨지므로 손대지 않고,
-- 여기서 해시만 교체한다.
--
-- 새 평문은 어디에도 커밋하지 않는다 — 로컬 `backend/.env` 의
-- SEED_ADMIN_PASSWORD 항목에만 존재한다. 아래 해시는 20자 랜덤 비밀번호의
-- BCrypt($2a$, cost 10)이라 사전 공격 대상이 아니다.
--
-- 다른 환경에 이미 배포했다면 이 마이그레이션에 의존하지 말고 각 환경에서
-- 직접 비밀번호를 재설정할 것.
-- =============================================================================

